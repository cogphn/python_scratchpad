from __future__ import annotations

import base64
import json
import os

from flask import Flask, g

from .client import SpacetimeClient, SpacetimeError
from .settings import Settings, cli_token


def _identity_from_token(token: str) -> str | None:
    """Pull ``hex_identity`` out of a Spacetime JWT without verifying it."""
    try:
        payload = token.split(".")[1]
        payload += "=" * (-len(payload) % 4)
        data = json.loads(base64.urlsafe_b64decode(payload))
        return data.get("hex_identity")
    except (IndexError, ValueError, TypeError):
        return None


def ensure_identity(settings: Settings) -> None:
    """Make sure we have a token to talk to the server with.

    Preference order: explicit setting / env var, the ``spacetime`` CLI's
    login token, and finally a fresh identity minted from the server.
    """
    if not settings.token:
        tok = cli_token()
        if tok:
            settings.token = tok
            settings.token_source = "spacetime CLI (~/.config/spacetime/cli.toml)"
    if not settings.token:
        try:
            data = SpacetimeClient(settings.host).create_identity()
        except SpacetimeError:
            return
        settings.token = data["token"]
        settings.identity = data["identity"]
        settings.token_source = "generated by stview"
    if settings.token and not settings.identity:
        settings.identity = _identity_from_token(settings.token)
    if not settings.token_source:
        settings.token_source = "stview config"
    settings.save()


def create_app(test_config: dict | None = None) -> Flask:
    app = Flask(__name__, instance_relative_config=False)
    app.config["SECRET_KEY"] = os.environ.get("STVIEW_SECRET_KEY", "stview-dev-key")
    app.config["MAX_CONTENT_LENGTH"] = 256 * 1024 * 1024  # wasm uploads
    if test_config:
        app.config.update(test_config)

    settings = Settings.load()
    ensure_identity(settings)
    app.extensions["stview_settings"] = settings

    @app.before_request
    def _attach_client() -> None:
        s: Settings = app.extensions["stview_settings"]
        g.settings = s
        g.client = SpacetimeClient(s.host, s.token)

    from . import views
    app.register_blueprint(views.bp)
    views.register_filters(app)
    return app
